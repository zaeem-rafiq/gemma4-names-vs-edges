"""Repository screening for Study A.

familiar: clone each listed repository, pin it to its last first-parent commit before a
          date (default 2025-01-01T00:00:00Z), count non-test Python lines, extract the
          call graph and apply the edge rule.
fresh:    scripted GitHub search (language:python, created on or after a date, minimum
          stars, licence filter, not a fork, not archived), ordered by stars, then the same
          pin / count / extract steps, plus a history check (no commit dated before the
          creation cutoff), until enough repositories pass. Every exclusion is logged with
          its reason.

Only metadata, commit ids, identifiers and call edges are written; no source code is
copied into the outputs.

Examples
  python -m ngraph.screen familiar --list familiar.txt --repos-dir R --out-dir O
  python -m ngraph.screen fresh --repos-dir R --out-dir O --want 22
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import subprocess
import sys
import time

from .extract import extract, file_lines, list_python_files, select_files

FLAG_PATTERNS = [
    r"\bport(?:ed)? (?:of|from)\b", r"\brewrite of\b", r"\brewritten from\b", r"\bfork of\b",
    r"\bforked from\b", r"auto-?generated", r"openapi[- ]generator", r"generated by (?:fern|stainless|speakeasy|openapi)",
    r"\bmirror of\b", r"\bunofficial (?:python )?(?:port|clone)\b", r"\bclone of\b",
]


def run(cmd, cwd=None, check=True) -> str:
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if check and r.returncode != 0:
        raise RuntimeError(f"{' '.join(cmd)} failed: {r.stderr.strip()[:500]}")
    return r.stdout


def clone(url: str, dest: str, sparse: bool = False) -> None:
    """Partial clone (no blobs until checkout). With sparse=True only Python files and the
    top-level README / LICENSE files are checked out, which keeps large app repositories cheap."""
    if os.path.isdir(os.path.join(dest, ".git")):
        return
    for attempt in range(4):
        try:
            run(["git", "clone", "-q", "--filter=blob:none", "--no-checkout", url, dest])
            break
        except RuntimeError:
            if attempt == 3:
                raise
            time.sleep(2 ** (attempt + 1))
    if sparse:
        run(["git", "sparse-checkout", "set", "--no-cone", "*.py", "/README*", "/readme*", "/LICENSE*",
             "/LICENCE*", "/License*", "/COPYING*"], cwd=dest)


def pin(dest: str, before: str) -> tuple[str, str]:
    sha = run(["git", "rev-list", "-1", "--first-parent", f"--before={before}", "HEAD"], cwd=dest).strip()
    if not sha:
        raise RuntimeError(f"no commit before {before}")
    run(["git", "checkout", "-q", "--force", sha], cwd=dest)
    date = run(["git", "show", "-s", "--format=%cI", sha], cwd=dest).strip()
    return sha, date


def earliest_date(dest: str, sha: str) -> str:
    """Earliest author or committer date of any commit reachable from sha (catches imported history)."""
    out = run(["git", "log", "--format=%aI%n%cI", sha], cwd=dest).split()
    stamps = sorted(dt.datetime.fromisoformat(s.replace("Z", "+00:00")).astimezone(dt.timezone.utc) for s in out if s)
    return stamps[0].strftime("%Y-%m-%dT%H:%M:%SZ") if stamps else ""


def count_lines(root: str) -> tuple[int, int]:
    files = list_python_files(root)
    n = 0
    for rel in files:
        try:
            with open(os.path.join(root, rel), encoding="utf-8", errors="replace") as fh:
                n += sum(1 for line in fh if line.strip())
        except OSError:
            continue
    return len(files), n


def readme_head(root: str, n_chars: int = 3000) -> str:
    for name in ("README.md", "README.rst", "README.txt", "README", "readme.md"):
        p = os.path.join(root, name)
        if os.path.isfile(p):
            with open(p, encoding="utf-8", errors="replace") as fh:
                return fh.read(n_chars)
    return ""


def license_head(root: str, n_chars: int = 120) -> str:
    """First characters of the LICENSE file at the pinned commit, for the licence log."""
    for name in sorted(os.listdir(root)):
        if re.match(r"^(licen[cs]e|copying)(\.\w+)?$", name, re.I) and os.path.isfile(os.path.join(root, name)):
            with open(os.path.join(root, name), encoding="utf-8", errors="replace") as fh:
                return name + ": " + " ".join(fh.read(n_chars * 2).split())[:n_chars]
    return ""


YEAR_RE = re.compile(r"(?:copyright(?:text)?:?|\(c\)|\u00a9)\s*(?:\(c\)|\u00a9)?\s*(?:by\s+)?((?:19|20)\d{2})", re.I)


def old_header_files(root: str, cutoff_year: int, n_lines: int = 40) -> list[str]:
    """Files whose first lines carry a copyright year before `cutoff_year` (likely copied or vendored)."""
    out = []
    for rel in list_python_files(root):
        try:
            with open(os.path.join(root, rel), encoding="utf-8", errors="replace") as fh:
                head = "".join(fh.readline() for _ in range(n_lines))
        except OSError:
            continue
        years = [int(y) for y in YEAR_RE.findall(head)]
        if years and min(years) < cutoff_year:
            out.append(rel)
    return out


def flags_for(text: str) -> list[str]:
    low = text.lower()
    return [p for p in FLAG_PATTERNS if re.search(p, low)]


def screen_one(url: str, label: str, repos_dir: str, out_dir: str, before: str, min_lines: int,
               min_edges: int, created_cutoff: str | None = None, meta: dict | None = None) -> dict:
    row = {"label": label, "url": url, **(meta or {})}
    dest = os.path.join(repos_dir, label)
    try:
        clone(url, dest, sparse=created_cutoff is not None)
        sha, date = pin(dest, before)
        row.update(commit=sha, commit_date=date, license_file=license_head(dest))
        if created_cutoff:
            first = earliest_date(dest, sha)
            row["earliest_commit_date"] = first
            if first and first < created_cutoff:
                row["status"], row["reason"] = "excluded", f"history has commits dated before {created_cutoff} ({first})"
                return row
        skip = []
        if created_cutoff:
            skip = old_header_files(dest, int(created_cutoff[:4]))
            all_lines = sum(file_lines(dest, f) for f in list_python_files(dest))
            old_lines = sum(file_lines(dest, f) for f in skip)
            row.update(old_header_files=len(skip), old_header_share=round(old_lines / max(all_lines, 1), 3))
            if all_lines and old_lines / all_lines > 0.25:
                row["status"], row["reason"] = "excluded", (
                    f"more than 25% of Python lines carry pre-{created_cutoff[:4]} copyright headers")
                return row
        files, finfo = select_files(dest, main_package_only=True, skip=skip)
        n_files, n_lines = finfo["n_files"], finfo["n_lines"]
        row.update(py_files=n_files, py_lines=n_lines, py_defs=finfo["n_defs"], kept_groups=finfo.get("kept_groups"),
                   dropped_groups={g: v for g, v in finfo["groups"].items() if g not in finfo.get("kept_groups", [])})
        if n_lines < min_lines:
            row["status"], row["reason"] = "excluded", f"fewer than {min_lines} non-test Python lines ({n_lines})"
            return row
        g = extract(dest, label, files=files, file_info=finfo)
        meta_g = g["graph"]
        row.update(nodes=len(g["nodes"]), edges=len(g["links"]), calls_seen=meta_g.get("calls_seen"),
                   calls_resolved=meta_g.get("calls_resolved"), parse_errors=meta_g.get("parse_errors"))
        os.makedirs(os.path.join(out_dir, "graphs"), exist_ok=True)
        with open(os.path.join(out_dir, "graphs", f"{label}.json"), "w") as fh:
            json.dump(g, fh)
        if len(g["links"]) < min_edges:
            row["status"], row["reason"] = "excluded", f"fewer than {min_edges} resolved call edges ({len(g['links'])})"
            return row
        fl = flags_for((row.get("description") or "") + "\n" + readme_head(dest))
        row["flags"] = fl
        row["status"] = "needs_review" if fl else "passed"
        return row
    except Exception as e:  # noqa: BLE001 - every failure is logged as an exclusion
        row["status"], row["reason"] = "excluded", f"error: {e}"[:400]
        return row


def gh_search(query: str, pages: int) -> tuple[int, list]:
    items, total = [], 0
    for page in range(1, pages + 1):
        out = run(["gh", "api", "-X", "GET", "search/repositories", "-f", f"q={query}", "-f", "sort=stars",
                   "-f", "order=desc", "-f", "per_page=100", "-f", f"page={page}"])
        data = json.loads(out)
        total = data.get("total_count", total)
        got = data.get("items", [])
        items.extend(got)
        if len(got) < 100:
            break
        time.sleep(2.5)  # stay well under the search rate limit
    return total, items


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("group", choices=["familiar", "fresh"])
    ap.add_argument("--list", help="familiar: file with lines 'label url'")
    ap.add_argument("--repos-dir", required=True)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--before", help="pin to the last first-parent commit before this time")
    ap.add_argument("--min-lines", type=int, default=3000)
    ap.add_argument("--min-edges", type=int, default=150)
    ap.add_argument("--created-after", default="2025-03-01")
    ap.add_argument("--min-stars", type=int, default=150)
    ap.add_argument("--licenses", default="mit,apache-2.0,bsd-3-clause")
    ap.add_argument("--pages", type=int, default=3)
    ap.add_argument("--want", type=int, default=22,
                    help="fresh: stop once this many repositories have passed or await README review")
    ap.add_argument("--max-size-kb", type=int, default=500_000)
    ap.add_argument("--candidates", help="fresh: reuse a saved candidate list instead of searching again")
    ap.add_argument("--review", help="fresh: JSON {full_name: {decision: include|exclude, reason}} from README review")
    a = ap.parse_args(argv)
    os.makedirs(a.repos_dir, exist_ok=True)
    os.makedirs(a.out_dir, exist_ok=True)
    log_path = os.path.join(a.out_dir, f"screen_{a.group}.jsonl")
    if a.group == "familiar":
        before = a.before or "2025-01-01T00:00:00Z"
        rows = []
        for line in open(a.list):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            label, url = line.split()[:2]
            row = screen_one(url, label, a.repos_dir, a.out_dir, before, 0, a.min_edges)
            rows.append(row)
            print(json.dumps({k: row.get(k) for k in ("label", "status", "reason", "py_lines", "nodes", "edges", "commit")}),
                  flush=True)
        with open(log_path, "w") as fh:
            for r in rows:
                fh.write(json.dumps(r) + "\n")
        return
    # fresh
    before = a.before or "2026-11-02T00:00:00Z"
    cutoff = f"{a.created_after}T00:00:00Z"
    review = json.load(open(a.review)) if a.review else {}
    if a.candidates:
        saved = json.load(open(a.candidates))
        ordered = saved["candidates"]
    else:
        ordered = search_candidates(a)
    rows, ok, used_labels = [], 0, set()
    for c in ordered:
        if ok >= a.want:
            break
        name = c["full_name"].split("/")[1]
        label = name if name not in used_labels else c["full_name"].replace("/", "__")
        meta = {k: c[k] for k in ("full_name", "stars", "created_at", "license", "size_kb", "description")}
        rv = review.get(c["full_name"], {})
        if c["created_at"] < cutoff:
            row = {"label": label, **meta, "status": "excluded", "reason": "created before cutoff"}
        elif rv.get("decision") == "exclude":
            row = {"label": label, **meta, "status": "excluded", "reason": f"README review: {rv.get('reason')}"}
        elif c["size_kb"] > a.max_size_kb:
            row = {"label": label, **meta, "status": "excluded",
                   "reason": f"repository larger than {a.max_size_kb} KB ({c['size_kb']} KB); not cloned"}
        else:
            row = screen_one(c["url"], label, a.repos_dir, a.out_dir, before, a.min_lines, a.min_edges, cutoff, meta)
            if row.get("status") == "needs_review" and rv.get("decision") == "include":
                row["status"], row["review"] = "passed", rv.get("reason")
            elif row.get("status") == "passed" and not rv:
                row["status"] = "needs_review"  # every fresh repository gets a README review before it counts
        rows.append(row)
        if row.get("status") in ("passed", "needs_review"):
            ok += 1
            used_labels.add(label)
        print(json.dumps({k: row.get(k) for k in ("label", "stars", "status", "reason", "py_lines", "edges", "flags")}),
              flush=True)
        with open(log_path, "w") as fh:
            for r in rows:
                fh.write(json.dumps(r) + "\n")


def search_candidates(a) -> list:
    queried_at = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    cands, totals = {}, {}
    for lic in a.licenses.split(","):
        q = (f"language:python created:>={a.created_after} stars:>={a.min_stars} license:{lic} "
             f"fork:false archived:false")
        total, items = gh_search(q, a.pages)
        totals[q] = total
        for it in items:
            cands[it["full_name"]] = {
                "full_name": it["full_name"], "stars": it["stargazers_count"], "created_at": it["created_at"],
                "license": (it.get("license") or {}).get("spdx_id"), "size_kb": it["size"],
                "description": (it.get("description") or "")[:300], "default_branch": it.get("default_branch"),
                "fork": it.get("fork"), "archived": it.get("archived"), "url": it["clone_url"],
            }
    ordered = sorted(cands.values(), key=lambda r: (-r["stars"], r["full_name"].lower()))
    with open(os.path.join(a.out_dir, "fresh_candidates.json"), "w") as fh:
        json.dump({"queried_at": queried_at, "queries": totals, "n": len(ordered), "candidates": ordered}, fh, indent=1)
    return ordered


if __name__ == "__main__":
    sys.exit(main())
